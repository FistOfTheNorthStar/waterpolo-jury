// Release signing: values come from keystore.properties (local, git-ignored)
// or from environment variables (CI). Without them the release build is unsigned.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(name: String): String? =
    (keystoreProps.getProperty(name) ?: System.getenv(name))?.takeIf { it.isNotBlank() }

